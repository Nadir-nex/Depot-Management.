'use strict';
// Party validation (Phase 11). Pure. Codes normalize uppercase; credit is
// NULL (unlimited) or non-negative minor units; phones are permissive.
const { ValidationError } = require('./errors');
const { PARTY_ROLES } = require('./vocabulary');
const { assertMinorUnits } = require('./money');

function cleanText(v) {
  return typeof v === 'string' ? v.trim() : '';
}

function validatePartyCode(code) {
  if (code === undefined || code === null || cleanText(code) === '') return null; // auto-generated by caller
  const c = cleanText(code).toUpperCase();
  if (c.length > 32) throw new ValidationError('party code must be at most 32 characters');
  if (!/^[A-Z0-9][A-Z0-9._-]*$/.test(c)) throw new ValidationError('party code must be alphanumeric with . _ - separators');
  return c;
}

function validateDisplayName(name) {
  const n = cleanText(name);
  if (!n) throw new ValidationError('party name is required');
  if (n.length > 200) throw new ValidationError('party name must be at most 200 characters');
  return n;
}

function validatePhone(phone) {
  const p = cleanText(phone);
  if (p.length > 32) throw new ValidationError('phone must be at most 32 characters');
  if (p !== '' && !/^[+0-9][0-9 .()/-]*$/.test(p)) throw new ValidationError('phone contains invalid characters');
  return p;
}

function validateEmail(email) {
  const e = cleanText(email);
  if (e.length > 200) throw new ValidationError('email must be at most 200 characters');
  if (e !== '' && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(e)) throw new ValidationError('email is not valid');
  return e;
}

function validateRoles(roles) {
  if (!Array.isArray(roles) || roles.length === 0) throw new ValidationError('at least one role is required');
  const clean = roles.map((r) => cleanText(r).toLowerCase());
  for (const r of clean) {
    if (!Object.values(PARTY_ROLES).includes(r)) throw new ValidationError(`unknown party role: ${r}`);
  }
  const unique = [...new Set(clean)];
  if (unique.length === 0) throw new ValidationError('at least one role is required');
  return unique;
}

function validateCreditLimit(limit) {
  if (limit === undefined || limit === null || limit === '') return null; // unlimited
  if (typeof limit === 'string' && limit.trim() !== '') {
    if (!/^-?\d+$/.test(limit.trim())) throw new ValidationError('credit limit must be an integer in minor units or empty');
    limit = Number(limit.trim());
  }
  if (!Number.isInteger(limit)) throw new ValidationError('credit limit must be an integer in minor units or empty');
  if (limit < 0) throw new ValidationError('credit limit cannot be negative');
  if (limit > 1_000_000_000_000) throw new ValidationError('credit limit is unreasonably large');
  return limit;
}

function validatePaymentTerms(days) {
  if (days === undefined || days === null || days === '') return null;
  if (typeof days === 'string' && days.trim() !== '') {
    if (!/^-?\d+$/.test(days.trim())) throw new ValidationError('payment terms must be a day count');
    days = Number(days.trim());
  }
  if (!Number.isInteger(days) || days < 0 || days > 3650) throw new ValidationError('payment terms must be 0..3650 days');
  return days;
}

function validateCreditAmount(amount) {
  if (typeof amount === 'string' && amount.trim() !== '') {
    if (!/^-?\d+$/.test(amount.trim())) throw new ValidationError('amount must be an integer in minor units');
    amount = Number(amount.trim());
  }
  return assertMinorUnits(amount);
}

module.exports = {
  validatePartyCode,
  validateDisplayName,
  validatePhone,
  validateEmail,
  validateRoles,
  validateCreditLimit,
  validatePaymentTerms,
  validateCreditAmount,
};
