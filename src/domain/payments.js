'use strict';
// Payment validation (Phase 16). Pure. Amounts are minor-unit integers;
// dates are business days (YYYY-MM-DD); methods/directions are vocabulary.
const { ValidationError } = require('./errors');
const { PAYMENT_METHODS, PAYMENT_DIRECTIONS } = require('./vocabulary');
const { assertMinorUnits } = require('./money');
const { validateDateString } = require('./dates');

function cleanText(v) {
  return typeof v === 'string' ? v.trim() : '';
}

function validatePaymentNo(no) {
  const n = cleanText(no);
  if (!n) return null; // auto-generated by caller
  if (n.length > 32) throw new ValidationError('payment number must be at most 32 characters');
  return n;
}

function validateDirection(d) {
  const v = cleanText(d);
  if (!Object.values(PAYMENT_DIRECTIONS).includes(v)) throw new ValidationError(`unknown payment direction: ${d}`);
  return v;
}

function validateMethod(m) {
  const v = cleanText(m);
  if (!Object.values(PAYMENT_METHODS).includes(v)) throw new ValidationError(`unknown payment method: ${m}`);
  return v;
}

function validatePaymentAmount(a) {
  if (typeof a === 'string') throw new ValidationError('payment amount must be an integer in minor units');
  if (!Number.isInteger(a)) throw new ValidationError('payment amount must be an integer in minor units');
  if (a <= 0) throw new ValidationError('payment amount must be positive');
  return assertMinorUnits(a);
}

function validatePaymentDate(d) {
  return validateDateString(d, 'payment_date');
}

function validateAccountCode(code) {
  const c = cleanText(code).toUpperCase();
  if (!c) throw new ValidationError('cash account code is required');
  if (c.length > 16) throw new ValidationError('cash account code must be at most 16 characters');
  if (!/^[A-Z0-9][A-Z0-9._-]*$/.test(c)) throw new ValidationError('cash account code must be alphanumeric with . _ - separators');
  return c;
}

function validateAllocationTarget(t) {
  const v = cleanText(t);
  if (v !== 'sales_invoice' && v !== 'purchase_receipt') {
    throw new ValidationError(`unknown allocation target: ${t}`);
  }
  return v;
}

module.exports = {
  validatePaymentNo,
  validateDirection,
  validateMethod,
  validatePaymentAmount,
  validatePaymentDate,
  validateAccountCode,
  validateAllocationTarget,
};
