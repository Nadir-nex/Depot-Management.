'use strict';
// Expense validation (Phase 17). Pure. Amounts are minor-unit integers;
// codes normalize uppercase like the other registries.
const { ValidationError } = require('./errors');
const { PAYMENT_METHODS } = require('./vocabulary');
const { assertMinorUnits } = require('./money');
const { validateDateString } = require('./dates');

function cleanText(v) {
  return typeof v === 'string' ? v.trim() : '';
}

function validateExpenseNo(no) {
  const n = cleanText(no);
  if (!n) return null; // auto-generated by caller
  if (n.length > 32) throw new ValidationError('expense number must be at most 32 characters');
  return n;
}

function validateCategoryCode(code) {
  const c = cleanText(code).toUpperCase();
  if (!c) throw new ValidationError('expense category code is required');
  if (c.length > 16) throw new ValidationError('expense category code must be at most 16 characters');
  if (!/^[A-Z0-9][A-Z0-9._-]*$/.test(c)) throw new ValidationError('expense category code must be alphanumeric with . _ - separators');
  return c;
}

function validateCategoryName(name) {
  const n = cleanText(name);
  if (!n) throw new ValidationError('expense category name is required');
  if (n.length > 100) throw new ValidationError('expense category name must be at most 100 characters');
  return n;
}

function validateExpenseAmount(a) {
  if (typeof a === 'string') throw new ValidationError('expense amount must be an integer in minor units');
  if (!Number.isInteger(a)) throw new ValidationError('expense amount must be an integer in minor units');
  if (a <= 0) throw new ValidationError('expense amount must be positive');
  return assertMinorUnits(a);
}

function validateExpenseMethod(m) {
  const v = cleanText(m);
  if (!Object.values(PAYMENT_METHODS).includes(v)) throw new ValidationError(`unknown payment method: ${m}`);
  return v;
}

function validateExpenseDate(d) {
  return validateDateString(d, 'expense_date');
}

module.exports = {
  validateExpenseNo,
  validateCategoryCode,
  validateCategoryName,
  validateExpenseAmount,
  validateExpenseMethod,
  validateExpenseDate,
};
